import Linker from './sqlite.js'; //Импортируем класс Linker — обёртку над SQLite из соседнего файла.
// У него есть методы: connect() — подключиться, run(sql) — выполнить запрос, close() — закрыть соединение.

// Принимает SQL-строку, открывает БД, выполняет запрос, закрывает соединение.
// Именно эта функция делает всю "грязную" работу — остальные (up/down) лишь делегируют ей вызов:
async function exec(sql) {
  // Защита от случайного вызова с undefined, null или пустой строкой.
  // typeof проверяет тип (строка ли это вообще):
  if (typeof sql !== 'string' || sql.trim().length === 0) {
    throw new Error('This migration failed the validation!');
  }

  let linker; // Объявляем переменную linker заранее, без значения (она равна undefined).
  // Это нужно, чтобы переменная была видна в блоке finally ниже

  try {
    linker = new Linker('./database.db'); // Создаём экземпляр Linker, указывая путь к файлу базы данных.
    await linker.connect(); // Асинхронно подключаемся к базе.
    return await linker.run(sql); // Выполняем SQL и возвращаем результат наружу.
  } catch (err) {
    // catch ловит ЛЮБУЮ ошибку из try: не удалось создать Linker, не удалось подключиться, не удалось выполнить SQL — всё попадёт сюда.
    console.log(err); // Видно в консоли: стек, сообщение, тип ошибки.
    throw new Error('This migration is failed.Try with another sql.'); // Пробрасываем новую ошибку с понятным текстом,  сохраняя оригинал в cause — чтобы не терять причину.
  } finally {
    // finally выполняется всегда — и при успехе, и при ошибке, и даже при return в try.
    // Здесь гарантированно закрываем соединение, чтобы не текла память/файловые дескрипторы.
    await linker.close(); // Проверяем, что linker был создан, иначе close() упадёт с TypeError.
  }
}
